#!/usr/bin/env node
/**
 * copy-qe-version.mjs — generate `src/qe-version.ts` from
 * `quantecon/VERSION.yml`.
 *
 * Mirrors the existing `copy:version` script for the upstream npm
 * version. The QuantEcon fork ships a separate `qe-vN` build identifier
 * alongside the upstream version (e.g. mystmd `1.9.1` + fork `qe-v6`);
 * `quantecon/VERSION.yml` is the canonical record, this script keeps
 * the bundled CLI in sync so `myst --version` prints both.
 *
 * Behaviour:
 *  - reads `qe_version` from `../../quantecon/VERSION.yml` (resolved
 *    from this script's location, not CWD, so it works from any
 *    `npm run` directory).
 *  - writes `src/qe-version.ts` exporting the value as a string.
 *  - if the file is missing, unreadable, or has no `qe_version`
 *    field, writes `null` so the version string falls back to the
 *    upstream-only form. Lets the script be a no-op on a future
 *    upstream branch that doesn't carry the `quantecon/` directory.
 *
 * Usage (from package.json):
 *   "copy:qe-version": "node scripts/copy-qe-version.mjs"
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';

const __dirname = dirname(fileURLToPath(import.meta.url));
const VERSION_YML = resolve(__dirname, '../../../quantecon/VERSION.yml');
const OUT = resolve(__dirname, '../src/qe-version.ts');

function readQeVersion() {
  if (!existsSync(VERSION_YML)) return null;
  try {
    const doc = yaml.load(readFileSync(VERSION_YML, 'utf8'));
    const v = doc?.qe_version;
    return typeof v === 'string' && v.length > 0 ? v : null;
  } catch {
    return null;
  }
}

const qeVersion = readQeVersion();
// JSON.stringify is the canonical safe primitive for converting a JS
// value to its source-text literal — handles `string` and `null` in
// one call and escapes special characters correctly. Belt-and-braces
// for future-proofing: today qe_version is constrained to `qe-vN`,
// but the script should still emit valid TS for any value.
const literal = JSON.stringify(qeVersion);
const contents = `// Auto-generated by scripts/copy-qe-version.mjs from quantecon/VERSION.yml.
// Source of truth is quantecon/VERSION.yml; do not hand-edit.
const qeVersion: string | null = ${literal};
export default qeVersion;
`;
writeFileSync(OUT, contents);
